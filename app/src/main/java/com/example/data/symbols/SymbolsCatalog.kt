    fun search(query: String): List<SymbolEntry> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()
        return categories.values.flatten().filter {
            it.nameAr.lowercase().contains(q) || it.symbol.contains(q)
        }
    }
